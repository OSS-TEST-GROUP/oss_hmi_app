// IDL enum int values are declaration-order-stamped (see
// idl/dds/lifecycle/LifecycleCommon.idl). Hard-coding the integers here keeps
// us decoupled from generated code, but a mismatch with the IDL would result
// in mis-labeled states — bump these in lockstep.

enum ServiceState {
  notRunning,         // 0
  initializing,       // 1
  running,            // 2
  runningNoResponse,  // 3
  terminating,        // 4
  unknown;

  static ServiceState fromInt(int? v) {
    switch (v) {
      case 0: return ServiceState.notRunning;
      case 1: return ServiceState.initializing;
      case 2: return ServiceState.running;
      case 3: return ServiceState.runningNoResponse;
      case 4: return ServiceState.terminating;
      default: return ServiceState.unknown;
    }
  }

  String get label {
    switch (this) {
      case ServiceState.notRunning:        return 'NOT_RUNNING';
      case ServiceState.initializing:      return 'INITIALIZING';
      case ServiceState.running:           return 'RUNNING';
      case ServiceState.runningNoResponse: return 'RUNNING_NO_RESPONSE';
      case ServiceState.terminating:       return 'TERMINATING';
      case ServiceState.unknown:           return 'UNKNOWN';
    }
  }
}

enum ServiceMode {
  normal,   // 0
  otaMode;  // 1

  int get value => this == ServiceMode.normal ? 0 : 1;

  String get label => this == ServiceMode.normal ? 'NORMAL' : 'OTA_MODE';

  static ServiceMode fromInt(int? v) =>
      v == 1 ? ServiceMode.otaMode : ServiceMode.normal;
}

enum OsType {
  ros2,     // 0
  agl,      // 1
  autosar;  // 2

  int get value {
    switch (this) {
      case OsType.ros2:    return 0;
      case OsType.agl:     return 1;
      case OsType.autosar: return 2;
    }
  }
}

class ServiceInfo {
  ServiceInfo({
    required this.name,
    this.state = ServiceState.unknown,
    this.recoveryPolicy = '',
    this.exitCode,
    this.lastChangedAt,
  });

  final String name;
  ServiceState state;
  String recoveryPolicy;
  int? exitCode;
  DateTime? lastChangedAt;
}

class LifecycleEvent {
  LifecycleEvent({
    required this.timestamp,
    required this.serviceName,
    required this.from,
    required this.to,
    this.kind = LifecycleEventKind.stateChange,
    this.detail,
  });

  final DateTime timestamp;
  final String serviceName;
  final ServiceState from;
  final ServiceState to;
  final LifecycleEventKind kind;
  final String? detail;
}

enum LifecycleEventKind {
  stateChange,
  startResponse,
  stopResponse,
  setModeResponse,
  updateList,
}
