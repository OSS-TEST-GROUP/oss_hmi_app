class ServiceInfo {
  ServiceInfo({
    required this.name,
    this.state = ServiceState.unknown,
    this.mode = ServiceMode.normal,
    this.recoveryPolicy = '',
    this.exitCode,
    this.containerName = '',
    this.lastChangedAt,
  });

  final String name;
  ServiceState state;
  ServiceMode mode;
  String recoveryPolicy;  // label form (e.g. 'ALWAYS') — see RecoveryPolicy.fromLabel
  int? exitCode;
  // F013: which container hosts this service (empty = native).
  // Populated from UpdateServiceListRequest.service_list[i].container_name.
  String containerName;
  DateTime? lastChangedAt;
}

